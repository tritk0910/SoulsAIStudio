using System.Diagnostics;
using System.Text;

namespace SoulsAiStudio.Bench;

/// <summary>One measured operation. Times in milliseconds, allocations in MB per op.</summary>
public sealed record BenchResult(
    string Section, string Name, int N,
    double FirstMs, double MedianMs, double P95Ms, double MinMs,
    double AllocMbPerOp, string Note);

/// <summary>
/// Minimal Stopwatch harness: 1 "first" run (includes JIT; OS file cache is usually already warm),
/// W warmup runs, N measured runs -> median / p95 / min + allocated bytes per op.
/// </summary>
public static class Harness
{
    public static readonly List<BenchResult> Results = new();
    public static readonly List<(string Section, string Key, string Value)> Facts = new();
    public static double Scale = 1.0; // --quick scales iteration counts down

    public static T Run<T>(string section, string name, int warmup, int iters, Func<T> op, string note = "")
    {
        iters = Math.Max(3, (int)Math.Round(iters * Scale));
        warmup = Math.Max(1, (int)Math.Round(warmup * Scale));

        var sw = Stopwatch.StartNew();
        T last = op();
        sw.Stop();
        double first = sw.Elapsed.TotalMilliseconds;

        for (int i = 1; i < warmup; i++) last = op();

        var times = new double[iters];
        long allocTotal = 0;
        for (int i = 0; i < iters; i++)
        {
            long a0 = GC.GetTotalAllocatedBytes(false);
            sw.Restart();
            last = op();
            sw.Stop();
            allocTotal += GC.GetTotalAllocatedBytes(false) - a0;
            times[i] = sw.Elapsed.TotalMilliseconds;
        }
        Array.Sort(times);
        double median = times.Length % 2 == 1
            ? times[times.Length / 2]
            : (times[times.Length / 2 - 1] + times[times.Length / 2]) / 2.0;
        double p95 = times[Math.Clamp((int)Math.Ceiling(0.95 * times.Length) - 1, 0, times.Length - 1)];
        var r = new BenchResult(section, name, iters, first, median, p95, times[0],
            allocTotal / (double)iters / (1024 * 1024), note);
        Results.Add(r);
        Console.WriteLine($"  [{section}] {name}: median {median:F3} ms, p95 {p95:F3} ms, first {first:F3} ms, alloc {r.AllocMbPerOp:F2} MB/op {note}");
        return last;
    }

    public static void Fact(string section, string key, object value)
    {
        Facts.Add((section, key, value?.ToString() ?? ""));
        Console.WriteLine($"  [{section}] {key} = {value}");
    }

    public static string PeakWorkingSetMb()
    {
        using var p = Process.GetCurrentProcess();
        p.Refresh();
        return $"{p.PeakWorkingSet64 / (1024.0 * 1024):F0} MB peak WS, {p.WorkingSet64 / (1024.0 * 1024):F0} MB current WS, {GC.GetTotalMemory(false) / (1024.0 * 1024):F0} MB managed heap";
    }

    public static string ToMarkdown(string machineInfo)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Bench results (auto-generated by tools/SoulsAiStudio.Bench)");
        sb.AppendLine();
        sb.AppendLine(machineInfo);
        sb.AppendLine();
        foreach (var section in Results.Select(r => r.Section).Concat(Facts.Select(f => f.Section)).Distinct())
        {
            sb.AppendLine($"## {section}");
            sb.AppendLine();
            var rs = Results.Where(r => r.Section == section).ToList();
            if (rs.Count > 0)
            {
                sb.AppendLine("| Operation | N | median ms | p95 ms | min ms | first ms | alloc MB/op | note |");
                sb.AppendLine("|---|---:|---:|---:|---:|---:|---:|---|");
                foreach (var r in rs)
                    sb.AppendLine($"| {r.Name} | {r.N} | {r.MedianMs:F3} | {r.P95Ms:F3} | {r.MinMs:F3} | {r.FirstMs:F3} | {r.AllocMbPerOp:F2} | {r.Note} |");
                sb.AppendLine();
            }
            var fs = Facts.Where(f => f.Section == section).ToList();
            if (fs.Count > 0)
            {
                sb.AppendLine("| Fact | Value |");
                sb.AppendLine("|---|---|");
                foreach (var f in fs)
                    sb.AppendLine($"| {f.Key} | {f.Value.Replace("|", "/")} |");
                sb.AppendLine();
            }
        }
        return sb.ToString();
    }
}
